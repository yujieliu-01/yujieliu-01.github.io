'use strict';
const fs=require('node:fs');
const path=require('node:path');
const probabilities=[.4,.5,.6],budget=100;
const bonuses=Array.from({length:budget+1},(_,t)=>Array.from({length:budget+1},(_,n)=>n?Math.sqrt(2*Math.log(Math.max(1,t))/n):Infinity));

// The policy receives observations only. Hidden probabilities belong to the simulator.
function select(counts,wins,t,c){
  const unplayed=counts.indexOf(0);
  if(unplayed>=0)return unplayed;
  let best=0,value=-Infinity;
  for(let arm=0;arm<3;arm++){
    const score=wins[arm]/counts[arm]+c*bonuses[t][counts[arm]];
    if(score>value){value=score;best=arm;}
  }
  return best;
}
function rng(seed){return()=>{let t=seed+=0x6D2B79F5;t=Math.imul(t^(t>>>15),t|1);t^=t+Math.imul(t^(t>>>7),t|61);return((t^(t>>>14))>>>0)/4294967296;};}
function simulate(streams,c){
  const counts=[0,0,0],wins=[0,0,0];
  for(let t=1;t<=budget;t++){
    const arm=select(counts,wins,t,c);
    wins[arm]+=streams[arm][counts[arm]++];
  }
  return {total:wins.reduce((a,b)=>a+b,0),counts,wins};
}
function evaluate(coefficients,games,seed){
  const random=rng(seed),sums=coefficients.map(()=>({sum:0,squares:0}));
  for(let game=0;game<games;game++){
    const p=probabilities.slice();
    for(let i=2;i>0;i--){const j=Math.floor(random()*(i+1));[p[i],p[j]]=[p[j],p[i]];}
    // Common independent potential rewards make coefficient comparisons less noisy.
    const streams=p.map(prob=>Array.from({length:budget},()=>Number(random()<prob)));
    coefficients.forEach((c,i)=>{const {total}=simulate(streams,c);sums[i].sum+=total;sums[i].squares+=total*total;});
  }
  return coefficients.map((c,i)=>{
    const mean=sums[i].sum/games,sd=Math.sqrt((sums[i].squares-games*mean*mean)/(games-1));
    return {c,games,seed,mean,standardDeviation:sd,mean95CI:[mean-1.96*sd/Math.sqrt(games),mean+1.96*sd/Math.sqrt(games)]};
  });
}
